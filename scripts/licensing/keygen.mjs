import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "../..");

console.log("Generating Ed25519 keypair for UAS Licensing Engine...");

const { publicKey, privateKey } = crypto.generateKeyPairSync("ed25519");

const privatePem = privateKey.export({ type: "pkcs8", format: "pem" });
const publicPem = publicKey.export({ type: "spki", format: "pem" });

// 1. Save private key outside distributable bundle (keys/uas-license-private.pem)
const keysDir = path.join(projectRoot, "keys");
if (!fs.existsSync(keysDir)) {
  fs.mkdirSync(keysDir, { recursive: true });
}

const privateKeyPath = path.join(keysDir, "uas-license-private.pem");
fs.writeFileSync(privateKeyPath, privatePem, { encoding: "utf8", mode: 0o600 });
console.log(`[OK] Private key saved to: ${privateKeyPath} (DO NOT DISTRIBUTE)`);

// 2. Write public key into src/lib/licensing/publicKey.ts
const publicKeyTsPath = path.join(projectRoot, "src", "lib", "licensing", "publicKey.ts");
const publicKeyTsContent = `// Ed25519 Public Key for UAS Accounting System Cryptographic Licensing
// Generated by scripts/licensing/keygen.mjs (npm run license:keygen)

export const UAS_LICENSE_PUBLIC_KEY = \`${publicPem.trim()}\`;
`;

fs.writeFileSync(publicKeyTsPath, publicKeyTsContent, "utf8");
console.log(`[OK] Public key updated in: ${publicKeyTsPath}`);

console.log("\nKey generation completed successfully!");
console.log("You can now issue licenses with: npm run license:issue -- --customer \"Acme\" --hwid \"<HWID>\"");
