import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, "..");

const schemaPath = path.join(projectRoot, "prisma", "schema.prisma");
const schemaContent = fs.readFileSync(schemaPath, "utf8");

if (!/provider\s*=\s*"sqlite"/.test(schemaContent)) {
  console.error("[ERROR] prisma/schema.prisma is not set to sqlite provider. Run `npm run db:sqlite` first.");
  process.exit(1);
}

// Always invoke the locally pinned Prisma CLI (6.19.3) via node — NEVER `npx prisma`!
const prismaEntrypoint = path.join(projectRoot, "node_modules", "prisma", "build", "index.js");
if (!fs.existsSync(prismaEntrypoint)) {
  console.error(`[ERROR] Pinned Prisma CLI not found at ${prismaEntrypoint}`);
  process.exit(1);
}

console.log("Generating authoritative SQLite DDL using pinned Prisma CLI (6.19.3)...");
const rawSql = execFileSync(
  process.execPath,
  [
    prismaEntrypoint,
    "migrate",
    "diff",
    "--from-empty",
    "--to-schema-datamodel",
    schemaPath,
    "--script",
  ],
  {
    cwd: projectRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }
).trim();

if (!rawSql || !rawSql.includes("CREATE TABLE")) {
  console.error("[ERROR] Prisma migrate diff produced empty or invalid SQL output.");
  process.exit(1);
}

const migrationName = "20261117000000_init";
const migrationsRoot = path.join(projectRoot, "prisma", "migrations");
const initMigrationDir = path.join(migrationsRoot, migrationName);
fs.mkdirSync(initMigrationDir, { recursive: true });

// Write migration_lock.toml
const lockToml = `# Please do not edit this file manually
# It should be added in your version-control system (i.e. Git)
provider = "sqlite"
`;
fs.writeFileSync(path.join(migrationsRoot, "migration_lock.toml"), lockToml, "utf8");

// Write UTF-8 migration.sql
const migrationSqlPath = path.join(initMigrationDir, "migration.sql");
fs.writeFileSync(migrationSqlPath, rawSql + "\n", "utf8");
console.log(`[OK] Wrote clean UTF-8 migration: ${migrationSqlPath} (${Buffer.byteLength(rawSql, "utf8")} bytes)`);

// Also write embedded TypeScript fallback so standalone builds can self-heal even if migrations folder is relocated
const embeddedTsPath = path.join(projectRoot, "src", "lib", "sqliteInitSql.ts");
const escapedSql = rawSql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
const embeddedTsContent = `// Auto-generated from prisma/schema.prisma by scripts/generate-sqlite-migration.mjs
// Pinned to Prisma 6.19.3 SQLite DDL — used as zero-dependency fallback for pure-runtime self-healing.

export const INITIAL_MIGRATION_NAME = "${migrationName}";

export const EMBEDDED_SQLITE_MIGRATION_SQL = \`${escapedSql}\`;
`;
fs.writeFileSync(embeddedTsPath, embeddedTsContent, "utf8");
console.log(`[OK] Wrote embedded runtime schema fallback: ${embeddedTsPath}`);
